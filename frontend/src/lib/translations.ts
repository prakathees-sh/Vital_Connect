import { TAMIL_NADU_DISTRICTS } from './districts';

export type Language = 'en' | 'ta';

// District lookup map
const districtMap: Record<string, { en: string; ta: string }> = {};
TAMIL_NADU_DISTRICTS.forEach((d) => {
  districtMap[d.name_en.toLowerCase()] = { en: d.name_en, ta: d.name_ta };
  districtMap[d.name_ta] = { en: d.name_en, ta: d.name_ta };
});

export const translateDistrict = (name: string | null | undefined, lang: Language): string => {
  if (!name) return '';
  const key = name.trim().toLowerCase();
  const entry = districtMap[key];
  if (entry) {
    return lang === 'ta' ? entry.ta : entry.en;
  }
  return name;
};

